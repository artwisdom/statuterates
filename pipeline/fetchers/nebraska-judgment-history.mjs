function isIsoDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

export function buildNebraskaOfficialHistory() {
  return OFFICIAL_HISTORY_ROWS.map(([effective_date, value]) => ({
    effective_date,
    value,
    value_text: `${value.toFixed(3)}%`,
    source_url: NEBRASKA_JUDICIAL_HISTORY_PDF_URL,
  }));
}

export function validateNebraskaHistory(history) {
  const errors = [];
  const sorted = [...history].sort((a, b) => a.effective_date.localeCompare(b.effective_date));
  if (sorted[0]?.effective_date !== '1987-01-01') {
    errors.push(`history must begin 1987-01-01, found ${sorted[0]?.effective_date || 'nothing'}`);
  }

  const seen = new Set();
  for (let index = 0; index < sorted.length; index++) {
    const point = sorted[index];
    if (!isIsoDate(point.effective_date)) errors.push(`invalid effective date ${point.effective_date}`);
    if (seen.has(point.effective_date)) errors.push(`duplicate effective date ${point.effective_date}`);
    seen.add(point.effective_date);
    if (!Number.isFinite(point.value) || point.value < 0 || point.value > 30) {
      errors.push(`invalid rate ${point.value} at ${point.effective_date}`);
    }
    if (index > 0 && point.effective_date <= sorted[index - 1].effective_date) {
      errors.push(`effective dates are not strictly increasing at ${point.effective_date}`);
    }
  }

  const transition = sorted.find((point) => point.effective_date === '2002-07-20');
  if (!transition || Math.abs(transition.value - 3.770) > 1e-9) {
    errors.push('history is missing the verified 2002-07-20 formula-transition rate of 3.770%');
  }
  return errors;
}
